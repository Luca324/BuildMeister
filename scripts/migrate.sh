#!/bin/sh

# Ждём пока БД реально будет готова принимать подключения
while ! nc -z database 5432; do
  echo "Ждём БД..."
  sleep 2
done

echo "БД готова! Запускаем приложение..."

# Запускаем приложение и перенаправляем вывод в временный файл
npm run start > /tmp/app.log 2>&1 &
APP_PID=$!

echo "Отслеживаем запуск приложения..."

# Ждём пока приложение полностью запустится (проверяем по логам)
while ! grep -q "Your website is running at" /tmp/app.log; do
  echo "Приложение ещё запускается..."
  sleep 2
done

echo "Приложение запущено! Запускаем миграции..."
npm run db:import &

# Ждём завершения всех фоновых процессов
wait

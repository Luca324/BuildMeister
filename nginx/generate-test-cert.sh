#!/bin/bash
# Скрипт для генерации временных самоподписанных SSL сертификатов для тестирования
# Используйте только для разработки! Для продакшена нужны реальные сертификаты.

echo "Генерация временных самоподписанных SSL сертификатов..."

# Создаем папку secrets если её нет
mkdir -p ../secrets

# Генерируем приватный ключ
openssl genrsa -out ../secrets/key.pem 2048

# Генерируем самоподписанный сертификат
openssl req -new -x509 -key ../secrets/key.pem -out ../secrets/cert.pem -days 365 \
  -subj "/C=NO/ST=Oslo/L=Oslo/O=BuildMeister/CN=buildmeister.no"

# Устанавливаем права доступа
chmod 644 ../secrets/cert.pem
chmod 600 ../secrets/key.pem

echo "✅ Временные сертификаты созданы в secrets/"
echo "⚠️  ВНИМАНИЕ: Это самоподписанные сертификаты только для тестирования!"
echo "⚠️  Браузер будет показывать предупреждение о безопасности."
echo "⚠️  Для продакшена замените их на реальные сертификаты от провайдера SSL."


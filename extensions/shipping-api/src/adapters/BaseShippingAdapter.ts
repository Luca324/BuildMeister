/**
 * Базовый абстрактный класс для всех адаптеров доставки
 * 
 * АРХИТЕКТУРА:
 * - Определяет единый интерфейс для всех провайдеров доставки
 * - Каждый провайдер (PostNord, Helthjem) наследуется от этого класса
 * - Гарантирует, что все провайдеры реализуют одинаковые методы
 * 
 * ПАТТЕРН ADAPTER:
 * - Адаптер преобразует интерфейс одного класса в интерфейс другого
 * - В нашем случае: преобразует формат данных EverShop в формат API провайдера
 * - Каждый провайдер имеет свой формат API, но мы используем единый интерфейс
 * 
 * ПРЕИМУЩЕСТВА:
 * - Легко добавлять новых провайдеров: просто создать новый класс
 * - Код работы с провайдерами не зависит от конкретной реализации
 * - Можно легко переключаться между провайдерами или использовать несколько одновременно
 * 
 * ИСПОЛЬЗОВАНИЕ:
 * - ShippingProviderService использует этот интерфейс для работы с любым провайдером
 * - Не нужно знать конкретный тип провайдера, достаточно знать BaseShippingAdapter
 * - Это полиморфизм в действии: один интерфейс, много реализаций
 */

import {
  ShippingOption,
  ShippingCalculationRequest,
  ShippingBookingRequest,
  ShippingBookingResult,
  TrackingInfo
} from './types.js';

export abstract class BaseShippingAdapter {
  /**
   * Возвращает уникальный код провайдера
   * 
   * Используется для:
   * - Идентификации провайдера в конфигурации
   * - Сохранения в БД (provider_code в таблице shipment)
   * - Выбора конкретного провайдера из списка
   * 
   * Примеры: 'postnord', 'helthjem'
   */
  abstract getProviderCode(): string;

  /**
   * Возвращает человекочитаемое название провайдера
   * 
   * Используется для:
   * - Отображения пользователю в интерфейсе
   * - Логирования и сообщений об ошибках
   * - Email уведомлений
   * 
   * Примеры: 'PostNord', 'Helthjem'
   */
  abstract getProviderName(): string;

  /**
   * Расчет стоимости доставки
   * 
   * ВЫЗЫВАЕТСЯ:
   * - При изменении адреса доставки на странице checkout
   * - Пользователь видит варианты доставки с ценами
   * 
   * ПРОЦЕСС:
   * 1. Получает адреса отправителя и получателя
   * 2. Рассчитывает общий вес и габариты товаров
   * 3. Вызывает API провайдера для получения вариантов доставки
   * 4. Нормализует ответ API в единый формат ShippingOption[]
   * 
   * @param request Данные для расчета (адреса, вес, габариты)
   * @returns Массив вариантов доставки с ценами и сроками
   */
  abstract calculateShipping(request: ShippingCalculationRequest): Promise<ShippingOption[]>;

  /**
   * Создание отправления в системе провайдера
   * 
   * ВЫЗЫВАЕТСЯ:
   * - После успешной оплаты заказа
   * - Автоматически через процессор orderCreateAfter
   * 
   * ПРОЦЕСС:
   * 1. Получает данные заказа и выбранный вариант доставки
   * 2. Вызывает API провайдера для создания отправления
   * 3. Получает tracking number, QR код, label и т.д.
   * 4. Возвращает результат для сохранения в БД
   * 
   * ВАЖНО:
   * - Вызывается только после оплаты (не при создании заказа)
   * - Если оплата не прошла, отправление не создается
   * - Ошибки логируются, но не блокируют создание заказа
   * 
   * @param request Данные заказа и выбранный вариант доставки
   * @returns Результат создания отправления (tracking number, QR код и т.д.)
   */
  abstract createBooking(request: ShippingBookingRequest): Promise<ShippingBookingResult>;

  /**
   * Отслеживание статуса отправления
   * 
   * ВЫЗЫВАЕТСЯ:
   * - При запросе статуса отправления пользователем или админом
   * - Может использоваться для автоматического обновления статуса заказа
   * 
   * ПРОЦЕСС:
   * 1. Вызывает API провайдера с tracking number
   * 2. Получает текущий статус и историю перемещений
   * 3. Нормализует статусы в формат EverShop
   * 4. Возвращает TrackingInfo для отображения
   * 
   * @param trackingNumber Трек-номер отправления
   * @returns Информация о текущем статусе и истории перемещений
   */
  abstract trackShipment(trackingNumber: string): Promise<TrackingInfo>;
}

